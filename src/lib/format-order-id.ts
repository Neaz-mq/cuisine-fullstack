/** cuid-এর শেষ কত অক্ষর নিয়ে দেখানোর আইডিটা বানানো হয়। */
const VISIBLE_LENGTH = 6;

export function formatOrderId(id: string) {
  return `#ORD-${id.slice(-VISIBLE_LENGTH).toUpperCase()}`;
}

/**
 * খোঁজার বাক্সে লেখা কথাটা থেকে সম্ভাব্য অর্ডার-আইডির টুকরোটা বার করে,
 * নাকি `null` যদি লেখাটা আইডি বলে মনে না হয়।
 *
 * ব্যবহারকারী যা-ই লিখুন সেটাই যেন চলে — তালিকা থেকে কপি করা
 * "#ORD-V7BT7G", হাতে লেখা "ord-v7bt7g", কিংবা কেবল "V7BT7G"।
 *
 * ⚠️ উপসর্গ ছাড়া লেখাটাকে আইডি ধরার শর্ত দুটো, আর দুটোই দরকারি:
 *
 *   • কোনো ফাঁক বা যতিচিহ্ন থাকা চলবে না — "Sojib Ali" যেন আইডি
 *     হিসেবে না খোঁজা হয়।
 *
 *   • অন্তত ছয় অক্ষর। এর চেয়ে ছোট হলে দুর্ঘটনাজনিত মিল ঘটে: cuid
 *     এলোমেলো ৩৬-ভিত্তিক অক্ষরের সারি, তাই "ali" খুঁজলে একেবারে
 *     সম্পর্কহীন কোনো অর্ডারের আইডির ভেতরে ওই তিন অক্ষর থেকে যাওয়া
 *     মোটেও অসম্ভব নয় — আর তখন নাম খুঁজতে গিয়ে অচেনা অর্ডার উঠে আসত।
 *     ছয় অক্ষরে সম্ভাবনাটা ৩৬⁶ ভাগের এক, অর্থাৎ কার্যত শূন্য।
 *
 * উপসর্গ (# বা ORD-) থাকলে ব্যবহারকারীর অভিপ্রায় নিয়ে সন্দেহ নেই,
 * তাই সেখানে দৈর্ঘ্যের শর্তটা শিথিল — অর্ধেক আইডি টাইপ করেও খোঁজা যায়।
 */
export function orderIdSearchToken(query: string): string | null {
  const trimmed = query.trim();
  if (!trimmed) return null;

  // "#", "ORD-", "#ORD-", "ord " — সবগুলো রূপই ছেঁটে ফেলা হয়।
  const prefix = /^#\s*(?:ord[-\s]?)?|^ord[-\s]/i;
  const hasPrefix = prefix.test(trimmed);
  const token = trimmed.replace(prefix, "").replace(/[^a-z0-9]/gi, "");

  if (!token) return null;
  if (hasPrefix) return token.length >= 2 ? token : null;

  // উপসর্গ নেই: লেখাটা পুরোটাই অক্ষর-সংখ্যা হতে হবে (অর্থাৎ ছাঁটার
  // পরেও অবিকৃত), আর যথেষ্ট লম্বা।
  return token.length >= VISIBLE_LENGTH && token === trimmed ? token : null;
}